import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url)).replace(/[\\/]$/, '');
const RECORD = 'data/winui-symbol.json';
export const OUTPUT = 'packages/winui-svelte/src/lib/symbol.ts';

export async function generate() {
	const doc = JSON.parse(await readFile(join(ROOT, RECORD), 'utf8'));
	const entries = doc.symbols.map((entry) => `\t${entry.name}: '${entry.glyph}'`).join(',\n');
	const content = `// Generated by \`pnpm symbol:build\` from data/winui-symbol.json. Do not edit.
//
// The pairs come from WinUI's own \`CSymbolIcon::ConvertSymbolValueToGlyph\`, which maps each
// \`Symbol\` member's legacy Segoe UI Symbol code point to the Segoe Fluent Icons point WinUI
// actually renders. The enum's own value is not the glyph: \`Symbol.Accept\` is E10B and draws
// E8FB. ADR 0012's amendment says why this is generated rather than transcribed.

/**
 * WinUI's \`Symbol\` enum, as the uppercase-hex code points the \`glyph\` prop takes, so a call
 * site writes \`glyph={Symbol.Accept}\`.
 *
 * This shadows the global \`Symbol\` in any module that imports it. The name is the WinUI
 * member's, which ADR 0009 says a mapped name follows, and a call site that needs the
 * language's \`Symbol\` still has \`globalThis.Symbol\`.
 */
export const Symbol = {
${entries}
} as const;

/** A member name of WinUI's \`Symbol\` enum. */
export type SymbolName = keyof typeof Symbol;
`;
	return { [OUTPUT]: content };
}

async function main() {
	const files = await generate();
	for (const [path, content] of Object.entries(files)) {
		await mkdir(dirname(join(ROOT, path)), { recursive: true });
		await writeFile(join(ROOT, path), content);
	}
	console.log(`written           ${OUTPUT}`);
}

// Only when run as a CLI: importing this module must not write anything, because C2
// imports it to ask what the output should be.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
	try {
		await main();
	} catch (error) {
		console.error(error.message);
		process.exit(1);
	}
}
